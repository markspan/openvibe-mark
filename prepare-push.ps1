#Requires -Version 5.1
<#
.SYNOPSIS
    Prepare a push: update .gitignore from PATCH_FILES.txt, then stage the files.

.DESCRIPTION
    Reads PATCH_FILES.txt (one repo-relative path per line, # = comment).
    Rewrites the UG-Lab section of .gitignore so every listed file is un-ignored,
    including all necessary parent directories.
    Then runs  git add  on each file so they are staged and ready to push.
    
    To add a new patched file: add it to PATCH_FILES.txt and re-run this script.
#>

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$Root = $PSScriptRoot

# ---------------------------------------------------------------------------
# Read manifest
# ---------------------------------------------------------------------------
$lines = Get-Content (Join-Path $Root "PATCH_FILES.txt")
$files = $lines | Where-Object { $_ -and -not $_.TrimStart().StartsWith('#') } | ForEach-Object { $_.Trim() }

if (-not $files) { Write-Warning "PATCH_FILES.txt is empty."; exit 0 }

Write-Host ""
Write-Host "=== prepare-push ===" -ForegroundColor Cyan
Write-Host "Files in manifest: $($files.Count)"

# ---------------------------------------------------------------------------
# Build the new UG-Lab section for .gitignore
# ---------------------------------------------------------------------------
$section = @()
$section += "# --- UG-Lab patch files (auto-generated by prepare-push.ps1) ---"
$section += "# Source of truth: PATCH_FILES.txt"

# Collect all unique parent directories that need to be un-ignored
$dirs = [System.Collections.Generic.HashSet[string]]::new()
foreach ($f in $files) {
    $parts = $f.Split('/')
    for ($i = 1; $i -lt $parts.Count; $i++) {
        $dirs.Add( ($parts[0..$($i-1)] -join '/') + '/' ) | Out-Null
    }
}

# Emit directory un-ignores, sorted by depth so parents come first
foreach ($d in ($dirs | Sort-Object { $_.Split('/').Count })) {
    $section += "!/$d"
}

# For each directory that contains our files, first block all its contents,
# then un-ignore only our specific files
$directParents = [System.Collections.Generic.HashSet[string]]::new()
foreach ($f in $files) {
    $parts = $f.Split('/')
    $parent = ($parts[0..$($parts.Count - 2)] -join '/') + '/'
    $directParents.Add($parent) | Out-Null
}
foreach ($d in ($directParents | Sort-Object)) {
    $section += "/$d*"
}
foreach ($f in ($files | Sort-Object)) {
    $section += "!/$f"
}
$section += "# --- end UG-Lab patch files ---"

# ---------------------------------------------------------------------------
# Rewrite .gitignore: keep everything outside the UG-Lab section
# ---------------------------------------------------------------------------
$gitignorePath = Join-Path $Root ".gitignore"
$existing = if (Test-Path $gitignorePath) {
    [System.IO.File]::ReadAllText($gitignorePath)
} else { "" }

# Strip any existing UG-Lab section
$pattern = '(?s)# --- UG-Lab patch files.*?# --- end UG-Lab patch files ---\r?\n?'
$stripped = [regex]::Replace($existing, $pattern, '')
$stripped  = $stripped.TrimEnd()

$newContent = $stripped + "`n`n" + ($section -join "`n") + "`n"
[System.IO.File]::WriteAllText($gitignorePath, $newContent, [System.Text.UTF8Encoding]::new($false))
Write-Host ".gitignore updated" -ForegroundColor Green

# ---------------------------------------------------------------------------
# Stage all patch files + the updated gitignore and manifest
# ---------------------------------------------------------------------------
Push-Location $Root
try {
    git add .gitignore PATCH_FILES.txt
    foreach ($f in $files) {
        $abs = Join-Path $Root ($f -replace '/', '\')
        if (Test-Path $abs) {
            git add $f
            Write-Host "  staged: $f" -ForegroundColor Green
        } else {
            Write-Warning "  not found, skipping: $f"
        }
    }
    Write-Host ""
    Write-Host "Ready to commit and push:" -ForegroundColor Cyan
    Write-Host "  git commit -m `"patch: $(Get-Date -Format 'yyyy-MM-dd')`""
    Write-Host "  git push"
} finally {
    Pop-Location
}
Write-Host ""